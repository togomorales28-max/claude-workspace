/**
 * Scans public/ajedrez/audio/voz for voice-over takes named after the
 * narration line ids (e.g. 05_rey.mp3) and writes the manifest that the
 * video reads. Warns when a take is longer than its window.
 *
 *   npm run ajedrez:voz
 */
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { LINES } from "../src/ajedrez/captions";
import { FPS, TOTAL_FRAMES } from "../src/ajedrez/timeline";

const ROOT = join(__dirname, "..");
const DIR = join(ROOT, "public", "ajedrez", "audio", "voz");
const MANIFEST = join(ROOT, "src", "ajedrez", "data", "voice-manifest.json");

const files = existsSync(DIR) ? readdirSync(DIR) : [];
const out: Record<string, { file: string; durationInFrames: number }> = {};

const probe = (path: string) => {
  const res = execFileSync(
    "npx",
    ["remotion", "ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
    { cwd: ROOT, encoding: "utf8" },
  );
  return parseFloat(res.trim());
};

LINES.forEach((line, i) => {
  const file = files.find((f) => /\.(mp3|wav|m4a|aac|ogg)$/i.test(f) && f.replace(/\.[^.]+$/, "") === line.id);
  if (!file) {
    console.log(`  ·  ${line.id}: sin archivo`);
    return;
  }
  const seconds = probe(join(DIR, file));
  const frames = Math.ceil(seconds * FPS);
  const windowEnd = LINES[i + 1]?.start ?? TOTAL_FRAMES;
  const max = windowEnd - line.start;
  out[line.id] = { file, durationInFrames: Math.min(frames, TOTAL_FRAMES - line.start) };
  const warn = frames > max ? `  ⚠ dura ${seconds.toFixed(2)} s, máximo ${(max / FPS).toFixed(2)} s` : "";
  console.log(`  ✓  ${line.id}: ${file} (${seconds.toFixed(2)} s)${warn}`);
});

writeFileSync(
  MANIFEST,
  JSON.stringify(
    {
      note: "Generated by `npm run ajedrez:voz`. Lists the voice-over files found in public/ajedrez/audio/voz.",
      files: out,
    },
    null,
    2,
  ) + "\n",
);
console.log(`\n${Object.keys(out).length}/${LINES.length} tomas de voz registradas en ${MANIFEST}`);
